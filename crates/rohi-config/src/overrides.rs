//! Explicit per-field overrides of a typed configuration section.
//!
//! A section is persisted as the fields the user chose explicitly, not as a
//! frozen copy of its whole value:
//! `effective = firmware defaults + overrides`. A field without an override
//! follows the defaults of the firmware that runs. The overrides only know how
//! to overlay themselves on a base value ([`ConfigOverrides::apply_to`]); the
//! firmware decides what the base is.

use core::fmt;

use minicbor::decode::{self, Decoder};
use minicbor::encode::{self, Encoder, Write};
use minicbor::{CborLen, Decode, Encode};

use crate::ConfigSection;

/// One field of a persisted section: not overridden, or an explicit value.
///
/// It is encoded as the bare value, and an absent field is `Default`, so an
/// untouched section is an empty CBOR map and a field appended later reads as
/// `Default` in older data. For an optional field the value itself can be
/// `None` (`Value(None)`), which is distinct from `Default`.
#[derive(Clone, PartialEq, Eq)]
pub enum Override<T> {
    /// The user did not override the field: the default applies.
    Default,
    /// The explicit value chosen by the user.
    Value(T),
}

// Not derived: the derive would require `T: Default`.
#[allow(clippy::derivable_impls)]
impl<T> Default for Override<T> {
    fn default() -> Self {
        Self::Default
    }
}

impl<T> Override<T> {
    /// Whether the field is explicitly overridden.
    pub const fn is_value(&self) -> bool {
        matches!(self, Self::Value(_))
    }

    /// The explicit value, if any.
    pub const fn as_value(&self) -> Option<&T> {
        match self {
            Self::Value(value) => Some(value),
            Self::Default => None,
        }
    }
}

impl<T: Clone> Override<T> {
    /// The explicit value, or `default` when the field is not overridden.
    pub fn value_or(&self, default: T) -> T {
        match self {
            Self::Value(value) => value.clone(),
            Self::Default => default,
        }
    }
}

impl<T: fmt::Debug> fmt::Debug for Override<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Default => f.write_str("Default"),
            Self::Value(value) => f.debug_tuple("Value").field(value).finish(),
        }
    }
}

impl<C, T: Encode<C>> Encode<C> for Override<T> {
    fn encode<W: Write>(
        &self,
        e: &mut Encoder<W>,
        ctx: &mut C,
    ) -> Result<(), encode::Error<W::Error>> {
        match self {
            Self::Default => e.null()?.ok(),
            Self::Value(value) => value.encode(e, ctx),
        }
    }

    fn is_nil(&self) -> bool {
        matches!(self, Self::Default)
    }
}

impl<'b, C, T: Decode<'b, C>> Decode<'b, C> for Override<T> {
    fn decode(d: &mut Decoder<'b>, ctx: &mut C) -> Result<Self, decode::Error> {
        T::decode(d, ctx).map(Self::Value)
    }

    fn nil() -> Option<Self> {
        Some(Self::Default)
    }
}

impl<C, T: CborLen<C>> CborLen<C> for Override<T> {
    fn cbor_len(&self, ctx: &mut C) -> usize {
        match self {
            Self::Default => 1,
            Self::Value(value) => value.cbor_len(ctx),
        }
    }
}

/// The persisted overrides of a typed section `C`.
///
/// Generated by [`config_overrides!`](crate::config_overrides). It is the
/// section that is stored; `C` is the effective value the runtime consumes.
pub trait ConfigOverrides<C>: ConfigSection + Clone + Default {
    /// The ids of the overridable fields.
    const FIELD_IDS: &'static [u32];

    /// Applies every override to `config`, which holds the firmware defaults.
    /// A field without an override is left as it is.
    fn apply_to(&self, config: &mut C);

    /// `C::default()`, the portable baseline, with every override applied.
    /// Not the authoritative product configuration: that is what the firmware
    /// provides as the base of [`apply_to`](Self::apply_to).
    fn over_default(&self) -> C
    where
        C: Default,
    {
        let mut config = C::default();
        self.apply_to(&mut config);
        config
    }

    /// Whether the field is overridden; `None` for an unknown field id.
    fn is_overridden(&self, id: u32) -> Option<bool>;

    /// Overrides the field with its current value in `config`. Returns
    /// `false` for an unknown field id.
    fn capture(&mut self, config: &C, id: u32) -> bool;

    /// Removes the override of the field, so that the default applies again.
    /// Returns `false` for an unknown field id.
    fn clear(&mut self, id: u32) -> bool;

    /// Whether no field is overridden.
    fn is_empty(&self) -> bool;
}

/// Defines the persisted overrides struct of a typed section.
///
/// ```ignore
/// rohi_config::config_overrides! {
///     /// Persisted overrides of the Wi-Fi section.
///     pub struct WifiOverrides for WifiConfig, version 1 {
///         1 => ssid: WifiSsid,
///         2 => password: Option<WifiPassword>,
///     }
/// }
/// ```
///
/// Every line maps a stable field id (also the CBOR map key, only ever added)
/// to a field of `WifiConfig` of the same name and type. The generated struct
/// holds an [`Override`] per field, derives the CBOR codec as a map, and
/// implements [`ConfigSection`] (its section id is the hash of the name of the
/// section type, `WifiConfig`) and [`ConfigOverrides`]; the generated code only
/// overlays the explicit overrides, it never decides the base. The calling crate
/// needs `minicbor` and must be allowed to access the fields of the section
/// type, so call it next to that type.
#[macro_export]
macro_rules! config_overrides {
    (
        $(#[$meta:meta])*
        $vis:vis struct $name:ident for $config:ident, version $version:literal {
            $($(#[$fmeta:meta])* $id:literal => $field:ident : $ty:ty),+ $(,)?
        }
    ) => {
        $(#[$meta])*
        #[derive(
            Clone,
            Debug,
            PartialEq,
            $crate::minicbor::Encode,
            $crate::minicbor::Decode,
            $crate::minicbor::CborLen,
        )]
        #[cbor(map)]
        $vis struct $name {
            $(
                $(#[$fmeta])*
                #[n($id)]
                pub $field: $crate::Override<$ty>,
            )+
        }

        impl ::core::default::Default for $name {
            fn default() -> Self {
                Self { $($field: $crate::Override::Default),+ }
            }
        }

        impl $crate::ConfigSection for $name {
            const ID: $crate::SectionId = $crate::SectionId::from_name(stringify!($config));
            const VERSION: u16 = $version;
        }

        impl $crate::ConfigOverrides<$config> for $name {
            const FIELD_IDS: &'static [u32] = &[$($id),+];

            fn apply_to(&self, config: &mut $config) {
                $(
                    if let $crate::Override::Value(value) = &self.$field {
                        config.$field = ::core::clone::Clone::clone(value);
                    }
                )+
            }

            fn is_overridden(&self, id: u32) -> ::core::option::Option<bool> {
                match id {
                    $($id => ::core::option::Option::Some(self.$field.is_value()),)+
                    _ => ::core::option::Option::None,
                }
            }

            fn capture(&mut self, config: &$config, id: u32) -> bool {
                match id {
                    $($id => {
                        self.$field =
                            $crate::Override::Value(::core::clone::Clone::clone(&config.$field));
                        true
                    })+
                    _ => false,
                }
            }

            fn clear(&mut self, id: u32) -> bool {
                match id {
                    $($id => {
                        self.$field = $crate::Override::Default;
                        true
                    })+
                    _ => false,
                }
            }

            fn is_empty(&self) -> bool {
                true $(&& !self.$field.is_value())+
            }
        }
    };
}

#[cfg(test)]
mod tests {
    extern crate std;

    use std::vec::Vec;

    use super::*;
    use crate::{decode_exact, encode_to_slice};

    #[derive(Clone, Debug, PartialEq)]
    struct Demo {
        name: Option<u8>,
        timeout: u32,
        flag: bool,
    }

    impl Default for Demo {
        fn default() -> Self {
            Self {
                name: Some(7),
                timeout: 1000,
                flag: false,
            }
        }
    }

    crate::config_overrides! {
        /// Test overrides.
        struct DemoOverrides for Demo, version 2 {
            1 => name: Option<u8>,
            2 => timeout: u32,
            4 => flag: bool,
        }
    }

    fn encode(value: &DemoOverrides) -> Vec<u8> {
        let mut buffer = [0u8; 32];
        let length = encode_to_slice(value, &mut buffer).unwrap();
        buffer[..length].to_vec()
    }

    #[test]
    fn untouched_overrides_are_the_defaults() {
        let overrides = DemoOverrides::default();
        assert!(overrides.is_empty());
        assert_eq!(overrides.over_default(), Demo::default());
        assert_eq!(encode(&overrides), [0xa0]);
        assert_eq!(decode_exact::<DemoOverrides>(&[0xa0]), Ok(overrides));
    }

    #[test]
    fn an_override_replaces_only_its_field() {
        let mut overrides = DemoOverrides::default();
        let config = Demo {
            timeout: 5,
            ..Demo::default()
        };
        assert!(overrides.capture(&config, 2));
        assert_eq!(overrides.is_overridden(2), Some(true));
        assert_eq!(overrides.is_overridden(1), Some(false));
        assert_eq!(
            overrides.over_default(),
            Demo {
                timeout: 5,
                ..Demo::default()
            }
        );
        assert_eq!(overrides.is_overridden(3), None);
        assert!(!overrides.capture(&config, 3));
        assert!(!overrides.clear(3));
    }

    #[test]
    fn clearing_an_override_restores_the_default() {
        let mut overrides = DemoOverrides::default();
        let config = Demo {
            timeout: 5,
            flag: true,
            ..Demo::default()
        };
        overrides.capture(&config, 2);
        overrides.capture(&config, 4);
        assert!(overrides.clear(2));
        assert_eq!(overrides.over_default().timeout, 1000);
        assert!(overrides.over_default().flag);
        assert!(!overrides.is_empty());
        overrides.clear(4);
        assert!(overrides.is_empty());
    }

    #[test]
    fn a_nullable_field_has_three_states() {
        let mut overrides = DemoOverrides::default();
        // Default: the default of the type, here `Some(7)`.
        assert_eq!(overrides.over_default().name, Some(7));
        // Explicit `None` differs from `Default`.
        overrides.name = Override::Value(None);
        assert_eq!(overrides.over_default().name, None);
        assert_eq!(overrides.is_overridden(1), Some(true));
        // Explicit `Some`.
        overrides.name = Override::Value(Some(9));
        assert_eq!(overrides.over_default().name, Some(9));
    }

    #[test]
    fn the_codec_keeps_the_three_states_apart() {
        let mut overrides = DemoOverrides {
            timeout: Override::Value(5),
            name: Override::Value(None),
            ..DemoOverrides::default()
        };
        let bytes = encode(&overrides);
        // {1: null, 2: 5}
        assert_eq!(bytes, [0xa2, 0x01, 0xf6, 0x02, 0x05]);
        assert_eq!(decode_exact::<DemoOverrides>(&bytes), Ok(overrides.clone()));

        overrides.name = Override::Value(Some(9));
        let bytes = encode(&overrides);
        assert_eq!(bytes, [0xa2, 0x01, 0x09, 0x02, 0x05]);
        assert_eq!(decode_exact::<DemoOverrides>(&bytes), Ok(overrides));
    }

    #[test]
    fn a_field_missing_in_stored_data_is_not_overridden() {
        let decoded = decode_exact::<DemoOverrides>(&[0xa1, 0x02, 0x05]).unwrap();
        assert_eq!(decoded.timeout, Override::Value(5));
        assert_eq!(decoded.name, Override::Default);
        assert_eq!(decoded.flag, Override::Default);
    }

    #[test]
    fn the_section_id_is_the_hash_of_the_section_type_name() {
        assert_eq!(
            <DemoOverrides as ConfigSection>::ID,
            crate::SectionId::from_name("Demo")
        );
        assert_eq!(<DemoOverrides as ConfigSection>::VERSION, 2);
        assert_eq!(DemoOverrides::FIELD_IDS, [1, 2, 4]);
    }

    #[test]
    fn overrides_are_applied_on_the_base_given_not_on_the_default() {
        let firmware = Demo {
            name: None,
            timeout: 50,
            flag: true,
        };
        let overrides = DemoOverrides {
            timeout: Override::Value(5),
            name: Override::Value(Some(1)),
            ..DemoOverrides::default()
        };
        let mut config = firmware.clone();
        overrides.apply_to(&mut config);
        assert_eq!(
            config,
            Demo {
                name: Some(1),
                timeout: 5,
                flag: true,
            }
        );
        let mut untouched = firmware.clone();
        DemoOverrides::default().apply_to(&mut untouched);
        assert_eq!(untouched, firmware);
        // The convenience helper is the portable baseline.
        assert_eq!(overrides.over_default().flag, Demo::default().flag);
    }

    #[test]
    fn value_or_picks_the_override() {
        assert_eq!(Override::Value(3).value_or(9), 3);
        assert_eq!(Override::<u8>::Default.value_or(9), 9);
    }
}
