use core::fmt;

const FNV64_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
const FNV64_PRIME: u64 = 0x0000_0100_0000_01b3;

/// Stable 64-bit identifier of a configuration section.
///
/// Identifiers are generated by `#[derive(ConfigSection)]` as the FNV-1a
/// 64-bit hash of the UTF-8 bytes of the Rust struct name (see
/// [`SectionId::from_name`]), without module or crate path, unless an explicit
/// `id` is given.
///
/// The hash algorithm and the struct names of persisted sections are part of
/// the persistent storage ABI: changing either changes the IDs and orphans the
/// stored data.
#[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct SectionId(pub u64);

impl SectionId {
    /// Hashes the struct `name` with FNV-1a 64 (offset basis `0xcbf29ce484222325`, prime
    /// `0x100000001b3`) over its UTF-8 bytes.
    pub const fn from_name(name: &str) -> Self {
        let bytes = name.as_bytes();
        let mut hash = FNV64_OFFSET;
        let mut i = 0;
        while i < bytes.len() {
            hash ^= bytes[i] as u64;
            hash = hash.wrapping_mul(FNV64_PRIME);
            i += 1;
        }
        Self(hash)
    }
}

impl fmt::Debug for SectionId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "SectionId({:#018x})", self.0)
    }
}

impl fmt::Display for SectionId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:#018x}", self.0)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fnv1a64_reference_vectors() {
        assert_eq!(SectionId::from_name("").0, 0xcbf2_9ce4_8422_2325);
        assert_eq!(SectionId::from_name("a").0, 0xaf63_dc4c_8601_ec8c);
        assert_eq!(SectionId::from_name("foobar").0, 0x8594_4171_f739_67e8);
    }

    // Changing any of these values is a breaking persistent storage change.
    #[test]
    fn section_id_golden_values() {
        assert_eq!(SectionId::from_name("Identity").0, 0x94d6_3573_d312_fe9b);
        assert_eq!(SectionId::from_name("WifiConfig").0, 0x3352_46ad_2024_8b26);
        assert_eq!(
            SectionId::from_name("ConnectivityConfig").0,
            0x9c57_015a_4066_2d0c
        );
    }

    #[test]
    fn id_is_const_evaluable() {
        const ID: SectionId = SectionId::from_name("WifiConfig");
        assert_eq!(ID.0, 0x3352_46ad_2024_8b26);
    }
}
