//! On-demand access to measurement snapshots.
//!
//! The `MeasurementStore` has exactly one owner task. Other tasks (the future
//! control layer included) never see the store; they ask the owner for a
//! snapshot through a [`MeasurementHandle`]:
//!
//! ```text
//! sensor tasks -> SensorEvent -> owner task (MeasurementStore)
//!                                      ^  |
//!                      snapshot request|  |snapshot
//!                                      |  v
//!                               MeasurementHandle
//! ```
//!
//! The owner generates every snapshot when it serves the request, with the
//! monotonic time of that moment, so `Valid`/`Stale` and `age_ms` are correct
//! at request time. The request path is bounded: one request slot and one
//! response slot, callers are serialized, and the owner never blocks on a
//! caller that gave up.

use embassy_sync::blocking_mutex::raw::RawMutex;
use embassy_sync::channel::Channel;
use embassy_sync::mutex::Mutex;
use embassy_sync::signal::Signal;

use crate::MeasurementsSnapshot;

/// Failure of a snapshot request.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum MeasurementServiceError {
    /// Another snapshot request is in flight; only [`MeasurementHandle::try_snapshot`] reports it.
    Busy,
}

/// Request/response channel between the owner task and its handles.
///
/// Place it in a `static`; all storage is inline and bounded.
pub struct MeasurementService<M: RawMutex> {
    requests: Channel<M, u32, 1>,
    responses: Signal<M, (u32, MeasurementsSnapshot)>,
    /// Held for the whole call; the value numbers the requests so that the
    /// response of an abandoned call is never mistaken for a later one.
    call: Mutex<M, u32>,
}

impl<M: RawMutex> MeasurementService<M> {
    /// Create an idle service.
    pub const fn new() -> Self {
        Self {
            requests: Channel::new(),
            responses: Signal::new(),
            call: Mutex::new(0),
        }
    }

    /// Handle used by other tasks to request snapshots.
    pub const fn handle(&self) -> MeasurementHandle<'_, M> {
        MeasurementHandle { service: self }
    }

    /// Wait for the next snapshot request. Owner side; cancel safe, so it can
    /// be used in a `select` next to the sensor event queue.
    pub async fn accept(&self) -> SnapshotRequest<'_, M> {
        SnapshotRequest {
            service: self,
            seq: self.requests.receive().await,
        }
    }
}

impl<M: RawMutex> Default for MeasurementService<M> {
    fn default() -> Self {
        Self::new()
    }
}

/// A pending snapshot request, to be answered by the owner.
#[must_use = "an unanswered request makes the caller wait"]
pub struct SnapshotRequest<'a, M: RawMutex> {
    service: &'a MeasurementService<M>,
    seq: u32,
}

impl<M: RawMutex> SnapshotRequest<'_, M> {
    /// Answer with a snapshot generated now by the owner.
    pub fn respond(self, snapshot: MeasurementsSnapshot) {
        self.service.responses.signal((self.seq, snapshot));
    }
}

/// Cheap, copyable interface to the `MeasurementStore` owner task.
pub struct MeasurementHandle<'a, M: RawMutex> {
    service: &'a MeasurementService<M>,
}

impl<M: RawMutex> Clone for MeasurementHandle<'_, M> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<M: RawMutex> Copy for MeasurementHandle<'_, M> {}

impl<M: RawMutex> MeasurementHandle<'_, M> {
    /// Current snapshot, generated by the owner when it serves the request.
    ///
    /// Waits while other requests are being served. The caller should bound
    /// the wait with its own timeout.
    pub async fn snapshot(&self) -> Result<MeasurementsSnapshot, MeasurementServiceError> {
        let mut seq = self.service.call.lock().await;
        Ok(self.call(&mut seq).await)
    }

    /// Like [`snapshot`](Self::snapshot) but fails with
    /// [`MeasurementServiceError::Busy`] instead of waiting for another
    /// request in flight.
    pub async fn try_snapshot(&self) -> Result<MeasurementsSnapshot, MeasurementServiceError> {
        let mut seq = self
            .service
            .call
            .try_lock()
            .map_err(|_| MeasurementServiceError::Busy)?;
        Ok(self.call(&mut seq).await)
    }

    async fn call(&self, seq: &mut u32) -> MeasurementsSnapshot {
        *seq = seq.wrapping_add(1);
        let seq = *seq;
        self.service.requests.send(seq).await;
        loop {
            let (answered, snapshot) = self.service.responses.wait().await;
            if answered == seq {
                return snapshot;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use core::pin::pin;

    use embassy_futures::join::join;
    use embassy_futures::poll_once;
    use embassy_sync::blocking_mutex::raw::NoopRawMutex;

    use super::*;
    use crate::runtime::Clock;
    use crate::sensor::Scd4xUpdate;
    use crate::testutil::block_on;
    use crate::{
        Celsius, MeasurementState, MeasurementStore, MeasurementUpdate, MonotonicTimestamp, Ppm,
        RelativeHumidity, SensorEvent, SensorKind,
    };

    type Service = MeasurementService<NoopRawMutex>;

    struct Clk(core::cell::Cell<u64>);

    impl Clock for Clk {
        fn now(&self) -> MonotonicTimestamp {
            MonotonicTimestamp::from_millis(self.0.get())
        }
    }

    fn scd4x(at: u64) -> SensorEvent {
        SensorEvent::Measurements(MeasurementUpdate::Scd4x(Scd4xUpdate {
            co2: Ppm(800.0),
            temperature: Celsius(21.0),
            humidity: RelativeHumidity(40.0),
            timestamp: MonotonicTimestamp::from_millis(at),
        }))
    }

    /// Serve exactly one request the way the owner task does.
    async fn serve_one(service: &Service, store: &MeasurementStore, clock: &Clk) {
        service.accept().await.respond(store.snapshot(clock.now()));
    }

    fn snapshot_at(
        service: &Service,
        store: &MeasurementStore,
        clock: &Clk,
    ) -> MeasurementsSnapshot {
        let handle = service.handle();
        let (snapshot, ()) = block_on(join(handle.snapshot(), serve_one(service, store, clock)));
        snapshot.unwrap()
    }

    #[test]
    fn snapshot_returns_current_values() {
        let service = Service::new();
        let clock = Clk(core::cell::Cell::new(1_000));
        let mut store = MeasurementStore::new();
        store.apply(scd4x(1_000));

        let snapshot = snapshot_at(&service, &store, &clock);
        assert_eq!(
            snapshot,
            store.snapshot(MonotonicTimestamp::from_millis(1_000))
        );
        assert_eq!(
            snapshot.measurements.scd4x.unwrap().co2.value,
            Some(Ppm(800.0))
        );
    }

    #[test]
    fn snapshot_uses_time_of_the_request() {
        let service = Service::new();
        let clock = Clk(core::cell::Cell::new(1_000));
        let mut store = MeasurementStore::new();
        store.apply(scd4x(1_000));
        let policy = store.freshness_policy(SensorKind::Scd4x);

        let first = snapshot_at(&service, &store, &clock);
        let co2 = first.measurements.scd4x.unwrap().co2;
        assert_eq!(co2.state, MeasurementState::Valid);
        assert_eq!(first.generated_at.millis, 1_000);
        assert_eq!(co2.updated_at, Some(MonotonicTimestamp::from_millis(1_000)));

        // Nothing changed in the store, only time passed.
        clock.0.set(1_000 + policy.stale_after_ms + 1);
        let second = snapshot_at(&service, &store, &clock);
        let co2 = second.measurements.scd4x.unwrap().co2;
        assert_eq!(co2.state, MeasurementState::Stale);
        assert_eq!(second.generated_at, clock.now());
        assert_eq!(
            second.measurements.scd4x.unwrap().co2.value,
            Some(Ppm(800.0))
        );
    }

    #[test]
    fn requests_do_not_mutate_the_store() {
        let service = Service::new();
        let clock = Clk(core::cell::Cell::new(2_000));
        let mut store = MeasurementStore::new();
        store.apply(scd4x(1_000));
        let before = store.snapshot(clock.now());

        for _ in 0..3 {
            snapshot_at(&service, &store, &clock);
        }
        assert_eq!(store.snapshot(clock.now()), before);
        assert!(before.measurements.bmx280.is_none());
    }

    #[test]
    fn owner_applies_events_between_requests() {
        let service = Service::new();
        let clock = Clk(core::cell::Cell::new(5_000));
        let mut store = MeasurementStore::new();

        assert!(
            snapshot_at(&service, &store, &clock)
                .measurements
                .scd4x
                .is_none()
        );
        store.apply(scd4x(4_900));
        let snapshot = snapshot_at(&service, &store, &clock);
        assert_eq!(
            snapshot.measurements.scd4x.unwrap().co2.value,
            Some(Ppm(800.0))
        );
    }

    #[test]
    fn request_waits_for_the_owner() {
        let service = Service::new();
        let handle = service.handle();
        let mut fut = pin!(handle.snapshot());
        assert!(poll_once(fut.as_mut()).is_pending());
    }

    #[test]
    fn concurrent_requests_are_serialized_and_try_reports_busy() {
        let service = Service::new();
        let clock = Clk(core::cell::Cell::new(10));
        let store = MeasurementStore::new();
        let handle = service.handle();

        let mut first = pin!(handle.snapshot());
        assert!(poll_once(first.as_mut()).is_pending());
        assert_eq!(
            block_on(handle.try_snapshot()),
            Err(MeasurementServiceError::Busy)
        );

        block_on(serve_one(&service, &store, &clock));
        assert!(block_on(first).is_ok());
        let (second, ()) = block_on(join(
            handle.try_snapshot(),
            serve_one(&service, &store, &clock),
        ));
        assert!(second.is_ok());
    }

    #[test]
    fn abandoned_request_does_not_poison_the_next_one() {
        let service = Service::new();
        let clock = Clk(core::cell::Cell::new(10));
        let store = MeasurementStore::new();
        let handle = service.handle();

        {
            let mut abandoned = pin!(handle.snapshot());
            assert!(poll_once(abandoned.as_mut()).is_pending());
        }
        // The owner answers the abandoned request; the owner does not block.
        block_on(serve_one(&service, &store, &clock));

        clock.0.set(77);
        let (snapshot, ()) = block_on(join(handle.snapshot(), serve_one(&service, &store, &clock)));
        assert_eq!(snapshot.unwrap().generated_at.millis, 77);
    }
}
