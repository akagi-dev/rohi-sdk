#![no_std]

//! Cryptographic identity of a Robonomics Open Hardware device.
//!
//! # Overview
//!
//! Every provisioned device has exactly one Ed25519 identity: a 32-byte
//! secret (the RFC 8032 secret key, also called seed) stored in the
//! [`Identity`] configuration section. The identity is **provisioned from the
//! host, never generated by the device**, and is the cryptographic identity
//! used to sign telemetry. The public key is derived from the secret and never
//! persisted.
//!
//! The master seed and the provisioning number exist only on the provisioning
//! host. The device stores only its own derived secret and never learns the
//! master seed, the number or the derivation path. This crate provides the
//! key, the [`Signer`] abstraction and Ed25519 signatures; message formats,
//! domain separation and replay protection belong to the protocol that is
//! signed. It is `no_std`, built on `ed25519-zebra`, and has no transport
//! (BLE, Wi-Fi, Meshtastic, ...) dependency.
//!
//! # Quick Example
//!
//! Sign with an identity and verify with its public key. On a device the
//! secret comes from the provisioning action, not from a constant.
//!
//! ```
//! use rohi_identity::{Identity, IdentityError, Signer};
//!
//! let identity = Identity::from_secret(&[7; 32]).unwrap();
//! let signer = identity.signer();
//! let signature = signer.sign(b"payload").unwrap();
//! assert!(identity.public_key().verify(b"payload", &signature).is_ok());
//!
//! // Another message does not verify with this signature.
//! assert_eq!(
//!     identity.public_key().verify(b"other", &signature),
//!     Err(IdentityError::InvalidSignature)
//! );
//!
//! // A device without an identity has no signer, and none is ever generated.
//! assert!(matches!(
//!     rohi_identity::IdentitySigner::provisioned(None),
//!     Err(IdentityError::NotProvisioned)
//! ));
//! ```
//!
//! # Core Concepts
//!
//! ```text
//! master SURI ──► rohi ──► hard derivation //<number> ──► derived Ed25519 secret
//!                                                               │ control protocol (provision action)
//!                                                               ▼
//!                               ConfigStore ◄── Identity section ◄── device
//!                                                               │
//!                                                        IdentitySigner ──► sign(exact bytes)
//! ```
//!
//! * **Secret**: [`Secret`] wraps the 32 bytes; it is zeroized on drop and
//!   its `Debug` prints `Secret(<redacted>)`. Every 32-byte value is a valid
//!   Ed25519 secret key.
//! * **Identity**: [`Identity`] is the persisted section; it holds only the
//!   secret.
//! * **Signer**: [`Signer`] signs exactly the given bytes and offers no way
//!   to get the private key out. [`IdentitySigner`] is the implementation
//!   backed by an [`Identity`].
//! * **Public key and signature**: [`PublicKey`] (32 bytes, displayed as `0x`
//!   + 64 hex digits) verifies a [`Signature`] (64 bytes).
//!
//! ## Signing
//!
//! The signer signs **exactly the given bytes**. Protocol semantics belong to
//! the connectivity protocol layer,
//! [`rohi-connectivity`](../rohi_connectivity/index.html): it serializes the
//! `core.v1.Message` once, signs the preimage `sensor_id ‖ nonce ‖ message`
//! with a [`Signer`] and wraps the result in a `crypto.v1.SignedEnvelope`,
//! with the payload bytes never decoded or re-encoded after signing.
//! Ed25519 signing is deterministic; verification in [`PublicKey::verify`] is
//! the `ed25519-zebra` one (ZIP 215 rules).
//!
//! ## Boot behaviour
//!
//! On boot the firmware reads the [`Identity`] section. If it is absent the
//! device is *not provisioned*: sensors, BLE control and diagnostics keep
//! working, and only operations that need the identity fail with
//! [`IdentityError::NotProvisioned`] (telemetry creates no frame). There is no
//! automatic generation fallback. The log shows only the public key, never the
//! secret.
//!
//! The firmware keeps the result as runtime state next to the signer: not
//! provisioned, provisioned with its public key, or unknown when the storage
//! could not be read. Provision and erase update it in the same step as the
//! commit, and the service reads only that state for its summary, issues and
//! status, so observing the identity does not read the persistent store. Only
//! an unknown state reads the store again, which lets a storage that was
//! unavailable at boot recover.
//!
//! ## Derivation (provisioning ABI)
//!
//! The derived identity is the Substrate hard derivation of the master with
//! the junction `//<number>`:
//!
//! ```text
//! number = 1    →  //1
//! number = 42   →  //42
//! number = 1000 →  //1000
//! ```
//!
//! * The path is exactly `//<number>`: no namespace (`//rohi//42`,
//!   `//sensor//42` are wrong). It must stay stable.
//! * The master is a Substrate secret URI (mnemonic phrase or `0x` seed,
//!   optional path and `///password`) read from a file. The `rohi` tool applies
//!   the master's own path and password first and then the hard junction
//!   `//<number>`.
//! * Derivation uses `sp-core` (`ed25519`), the same algorithm as
//!   `Pair::from_string("<suri>//<number>")`.
//! * The same master and number give the same identity on every machine and in
//!   every future version, so an identity can be restored after flash
//!   replacement without backing up each derived key.
//! * **The number must be unique within one master hierarchy.** Using it for
//!   two active devices creates duplicate identities; the firmware cannot
//!   detect that because the number is never sent to it.
//!
//! The derivation lives on the host, in the `rohi` tool
//! (`rohi::derive_identity(suri, number)`, which returns a `DerivedIdentity`,
//! available with the `provision` feature of the `rohi` crate). Golden vectors
//! for the public development phrase
//! (`bottom drive obey lake curtain smoke basket hold race lonely fit walk`,
//! never a production master) are pinned in
//! `tools/rohi/src/provision/tests.rs`:
//!
//! | Number | Public key |
//! |-------:|------------|
//! | 1 | `0xbf3a763d817cee09bf785b9cc6118f58dab5c03f3ace6d524899bcb28ac74f27` |
//! | 2 | `0x276b9ce3c58b9f009f4f1f2ae5c7e9a599796246165df52f2d8b857fcecb1a40` |
//! | 42 | `0x8743ca72162320542b15ef0e66995fac97cd295626627046c41f64f796bcf2f3` |
//!
//! # Architecture & Integration
//!
//! | Where | What |
//! |-------|------|
//! | [`rohi_config`] | The [`Identity`] section lives in the normal configuration store (A/B transactional writes, CRC, power-loss recovery); see [`Identity`] for the storage contract. |
//! | [`rohi_service`] | [`IdentityService`] is the `identity` service of the status and action planes over an [`IdentityStore`] that the firmware implements. |
//! | [`rohi-control`](../rohi_control/index.html) | Carries the `provision` and `erase` requests from the `rohi` tool; link policies decide who may call them. |
//! | [`rohi-connectivity`](../rohi_connectivity/index.html) | Signs every telemetry frame through a `FrameSigner`; every [`Signer`] with [`IdentityError`] as error is one. |
//! | Altruist Urban firmware | The `identity` module loads the identity at boot and keeps an [`IdentitySigner`] as runtime state (`IdentityHandle::sign`, and a `StaticSigner` for telemetry that follows provisioning and erase). |
//!
//! The signer is updated by the **configuration owner task** in the same step
//! as the commit or removal of the [`Identity`] section, with no `.await` in
//! between. Provision and erase therefore follow the
//! [durable-mutation rule](../rohi_sdk/cancellation/index.html#durable-mutation): a
//! request cancelled before it was queued changed nothing; cancelled
//! afterwards, the operation is logically completed and the signer agrees with
//! the stored identity.
//!
//! The secret passes through fixed-size buffers of the configuration channel
//! and the BLE request path, which are not scrubbed after use.
//!
//! ## Control plane and command line
//!
//! The control-plane contract (requests, privileges, errors) is documented on
//! [`IdentityService`]. The `rohi` tool has no identity command; the generic
//! `status` and `action` commands are used:
//!
//! ```text
//! rohi status identity                      # state and public key; never the secret
//! rohi action identity provision secret=-   # 32-byte secret as hex, read from stdin or a hidden prompt
//! rohi action identity erase
//! ```
//!
//! The secret is derived on the host with `rohi::derive_identity(suri, number)`
//! (the library of the `rohi` crate) and only the derived secret is sent. The
//! master seed, the number and the derivation path are never sent, stored or
//! logged, and a malformed secret is not echoed in the error. After
//! provisioning, compare the public key reported by `status identity` with
//! `DerivedIdentity::public_key()`. `rohi system factory_reset` formats the
//! configuration storage and so erases the identity too.
//!
//! ## Security status
//!
//! Provisioning moves a private key over BLE, so it must only be accepted on a
//! protected link. **BLE pairing is not implemented yet**: the Altruist Urban
//! firmware runs [`OpenPolicy`](../rohi_control/struct.OpenPolicy.html), so
//! today anyone in radio range can provision or erase an identity. Provision
//! and erase use a dedicated
//! [`Privilege::Provision`](../rohi_control/enum.Privilege.html#variant.Provision)
//! (erase: `Mutate`), so
//! [`RequireEncryption`](../rohi_control/struct.RequireEncryption.html) and
//! [`RequireAuthenticated`](../rohi_control/struct.RequireAuthenticated.html)
//! already reject them on an unprotected link with `PERMISSION_DENIED` (covered
//! by host tests); enabling pairing and switching the firmware policy is the
//! remaining step. Provision devices in a trusted place until then. The link
//! policies are described in [`rohi-control`](../rohi_control/index.html).
//!
//! # API Navigation
//!
//! | Item | Role |
//! |------|------|
//! | [`Secret`] | Zeroized on drop; `Debug` prints `Secret(<redacted>)`; no `Display`. |
//! | [`Identity`], [`SECRET_LEN`] | The `Identity` configuration section; holds the 32-byte secret only. [`Identity::public_key`], [`Identity::signer`]. The storage contract is on its page. |
//! | [`PublicKey`], [`Signature`], [`PUBLIC_KEY_LEN`], [`SIGNATURE_LEN`] | 32 / 64 raw bytes. [`PublicKey`] displays as `0x` + 64 hex digits and verifies signatures. |
//! | [`Signer`] | [`Signer::public_key`] and [`Signer::sign`]; there is no way to get the private key out of it. |
//! | [`IdentitySigner`] | [`Signer`] backed by an [`Identity`]; `IdentitySigner::provisioned(None)` is [`IdentityError::NotProvisioned`]. |
//! | `MockSigner` | Test signer (feature `mock`). |
//! | [`IdentityService`], [`IdentityStore`], [`IdentityStoreError`] | The `identity` service of the control plane and the persistence the firmware implements behind it. |
//! | [`IdentityError`] | Failures of keys, signatures and provisioning. |
//!
//! Everything is re-exported at the root; the only public modules are the
//! constant modules [`action_field`] and [`status_field`] (field ids of the
//! `identity` service). The private modules are `identity` (the section),
//! `secret`, `keys` ([`PublicKey`], [`Signature`]), `signer`, `service` (the
//! control-plane service) and `error`.
//!
//! # Guarantees & Limitations
//!
//! * **Secret handling**: [`Secret`] and [`IdentitySigner`] zeroize their key
//!   on drop and never print it; no status field or action result contains
//!   the secret. Copies in transport buffers are not scrubbed (see above).
//! * **One identity**: provisioning never replaces an existing identity
//!   ([`IdentityError::AlreadyProvisioned`] at the crate level, `REJECTED`
//!   `already_provisioned` on the control plane); erase first.
//! * **Persistent ABI**: section `Identity` version 1, ID
//!   `0x94d63573d312fe9b`, CBOR `[bytes(32)]`; see [`Identity`].
//! * **Errors**: [`IdentityError`] for keys and signatures;
//!   [`IdentityStoreError`] for the storage behind the service.
//! * **Features**: `std` enables `std` support of the cryptographic
//!   dependencies for host tools; `mock` adds `MockSigner` for tests of signer
//!   consumers. Both are off by default.
//! * **Not in scope**: automatic device-side generation, per-sensor keypairs,
//!   certificates, multiple identities, key rotation, a secure element,
//!   storing the number on the device and remote master storage. Message
//!   formats and uplink belong to `rohi-connectivity`.
//!
//! ## Validation level
//!
//! Host-tested: signing and RFC 8032 vectors, persistence across store
//! reopen, the service actions and the derivation vectors (`cargo test -p
//! rohi-identity`). The firmware builds for ESP32 targets in CI, but the
//! hardware procedure below has **no recorded results**: identity is
//! *not verified on hardware* (see the [support
//! matrix](https://rohi.akagi.dev/support/matrix.html)).
//!
//! Procedure for Altruist Urban hardware:
//!
//! 1. Fresh Altruist Urban: `rohi status identity` reports *not provisioned*;
//!    sensors and BLE diagnostics work.
//! 2. `rohi action identity provision secret=-` with the secret derived from
//!    `<test-master>`: host and device public keys match.
//! 3. Reboot: `rohi status identity` returns the same public key. Change
//!    unrelated configuration, reboot: unchanged.
//! 4. `rohi action identity erase`: state becomes *not provisioned*, signing
//!    fails with [`IdentityError::NotProvisioned`], sensors keep running.
//! 5. Provision again with the same master and number: the original public key
//!    is restored.

